// Optional browser verification; see Docs/Testing/BROWSER_VERIFICATION.md.
const { chromium } = require(process.env.GLAUX_PLAYWRIGHT_MODULE || 'playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const repo = path.resolve(__dirname, '..');
const output = process.env.GLAUX_QA_OUTPUT || path.join(repo, 'artifacts/browser-qa');
const baseURL = (process.env.GLAUX_BASE_URL || 'http://127.0.0.1:5173').replace(/\/$/, '');
(async () => {
  await fs.mkdir(output, {recursive:true});
  const browser = await chromium.launch({executablePath:process.env.GLAUX_CHROMIUM_EXECUTABLE || undefined,headless:true});
  const page = await browser.newPage({viewport:{width:1100,height:1200},acceptDownloads:true});
  const errors=[]; const checks=[];
  page.on('pageerror', err => errors.push(err.message));
  const check=(name,passed)=>{assert(passed,name);checks.push(name);};
  const select = async (id,name) => {
    await page.locator('#example-select').selectOption(id);
    await page.getByRole('heading',{name,exact:true}).waitFor();
  };
  await page.goto(`${baseURL}/`);
  await page.getByRole('heading',{name:'TRSS ETU-II',exact:true}).waitFor();
  await page.getByRole('tab',{name:'Equipment',exact:true}).click();
  let content = await page.locator('#details-panel-equipment').innerText();
  check('TRSS equipment selections and orientation',content.includes('SEISMIC/ACOUSTIC')&&content.includes('IRID-II')&&content.includes('0 deg'));
  await page.screenshot({path:`${output}/ui-trss-equipment.png`,fullPage:true});
  await page.locator('#details-panel-equipment .fact-source summary').first().click();
  await page.getByRole('tab',{name:'Condition',exact:true}).click();
  content = await page.locator('#details-panel-condition').innerText();
  check('TRSS condition retains estimator basis',content.includes('100.0 %')&&content.includes('Collecting data for battery lifespan calculation'));
  await page.screenshot({path:`${output}/ui-trss-condition.png`,fullPage:true});
  await page.getByText('Estimate inputs and source values',{exact:true}).click();
  content=await page.locator('#details-panel-condition').innerText();
  check('Estimator input values remain accessible separately',content.includes('9 V')&&content.includes('25 Cel'));
  await page.getByText('Estimate inputs and source values',{exact:true}).click();
  await page.getByRole('tab',{name:'Equipment',exact:true}).click();
  check('Open fact disclosure survives tab rerender',await page.locator('#details-panel-equipment .fact-source').first().evaluate(n=>n.open));
  await page.getByRole('tab',{name:'Equipment',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  check('Arrow navigation activates and focuses Condition',await page.locator('#details-tab-condition').evaluate(n=>n.getAttribute('aria-selected')==='true'&&document.activeElement===n));
  await page.keyboard.press('Home');
  check('Home activates and focuses Overview',await page.locator('#details-tab-overview').evaluate(n=>n.getAttribute('aria-selected')==='true'&&document.activeElement===n));
  await page.keyboard.press('End');
  check('End activates and focuses Condition',await page.locator('#details-tab-condition').evaluate(n=>n.getAttribute('aria-selected')==='true'&&document.activeElement===n));
  await select('core2','OmniSense Core2');
  await page.getByRole('tab',{name:'Equipment',exact:true}).click();
  content = await page.locator('#details-panel-equipment').innerText();
  check('Core2 reported transducers retained', ['Magnetic','Seismic (ext)','Detection Switch 1','Detection Switch 2','Control Switch'].every(s=>content.includes(s)));
  await page.screenshot({path:`${output}/ui-core2-equipment.png`,fullPage:true});
  await page.getByRole('tab',{name:'Condition',exact:true}).click();
  content = await page.locator('#details-panel-condition').innerText();
  check('Core2 condition does not borrow Core5 voltage',!content.includes('15.43')&&content.toLowerCase().includes('no'));
  await select('core5','OmniSense Core5ADS');
  content = await page.locator('#details-panel-condition').innerText();
  check('Core5 reported voltage, kind, raw source clock and CPB',content.includes('15.43 V')&&content.includes('DC')&&content.includes('12/30/99 05:00:00')&&content.includes('CPB')&&!content.includes('GPS'));
  await page.screenshot({path:`${output}/ui-core5-condition.png`,fullPage:true});
  await page.locator('.remote-source > summary').click();
  await page.locator('#resource-url').fill('https://typed.example/systems/demo');
  await page.getByRole('button',{name:'Standard view',exact:true}).click();
  check('Mode focus retained',await page.getByRole('button',{name:'Standard view',exact:true}).evaluate(n=>document.activeElement===n));
  check('Draft URL preserved across mode change',await page.locator('#resource-url').inputValue()==='https://typed.example/systems/demo');
  check('Remote form disclosure preserved',await page.locator('.remote-source').evaluate(n=>n.open));
  content = await page.locator('.standard-view').innerText();
  check('Standard mode exposes definitions, units and source paths',content.includes('15.43 V')&&content.includes('Definition:')&&content.includes('/characteristics/')&&content.includes('Relationships and links'));
  await page.locator('.capture > summary').first().click();
  await page.getByText('Original response text',{exact:true}).click();
  const original = await fs.readFile(`${repo}/public/fixtures/omnisense-core5ads.json`);
  check('Original response text preserved',await page.locator('.capture-part').filter({has:page.getByText('Original response text',{exact:true})}).locator('pre').textContent()===original.toString());
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download original body',exact:true}).click();
  const download=await downloadPromise; const downloaded=await fs.readFile(await download.path());
  check('Downloaded original body is byte-identical',downloaded.equals(original));
  await select('mpss','MPSS technical-description contract example');
  await page.getByRole('button',{name:'Operator view',exact:true}).click();
  await page.getByRole('tab',{name:'Overview',exact:true}).click();
  content=await page.locator('#details-panel-overview').innerText();
  check('MPSS technical-description binding renders four contract fields',['Example Test Manufacturer','Synthetic Bench Model A','test-hw-1','test-fw-1'].every(s=>content.includes(s)));
  await page.screenshot({path:`${output}/ui-mpss-overview.png`,fullPage:true});
  const base=JSON.parse(original.toString()); base.id='browser-unknown-source'; base.label='<img src=x onerror=window.injected=true>'; base.unfamiliar={marker:'retain-this-unknown-content'};
  await page.route('**/browser-test/unknown',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(base)}));
  await page.locator('#resource-url').fill(`${baseURL}/browser-test/unknown`);
  await page.getByRole('button',{name:'Load resource',exact:true}).click();
  await page.getByRole('heading',{name:base.label,exact:true}).waitFor();
  check('Source strings cannot inject markup',await page.evaluate(()=>!window.injected&&document.querySelectorAll('.card-header h2 img').length===0));
  check('Remote source is not mislabeled synthetic',await page.locator('.source-notice').innerText().then(s=>s.startsWith('Remote source')));
  await page.getByRole('button',{name:'Standard view',exact:true}).click();
  await page.locator('.capture > summary').first().click();
  await page.getByText('Parsed JSON including unfamiliar fields',{exact:true}).click();
  check('Unfamiliar JSON content remains accessible',await page.locator('.capture-part').filter({has:page.getByText('Parsed JSON including unfamiliar fields',{exact:true})}).locator('pre').innerText().then(s=>s.includes('retain-this-unknown-content')));
  let release; const gate=new Promise(resolve=>release=resolve);
  await page.route('**/browser-test/slow',async route=>{await gate;try{await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({...base,label:'STALE RESPONSE'})});}catch{}});
  await page.locator('#resource-url').fill(`${baseURL}/browser-test/slow`);
  await page.getByRole('button',{name:'Load resource',exact:true}).click();
  await select('core2','OmniSense Core2'); release();
  await page.waitForTimeout(150);
  check('Switching source rejects stale in-flight response',await page.getByRole('heading',{name:'OmniSense Core2',exact:true}).count()===1&&await page.getByRole('heading',{name:'STALE RESPONSE',exact:true}).count()===0);
  await page.getByRole('button',{name:'Operator view',exact:true}).click();
  await page.getByRole('tab',{name:'Equipment',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:`${output}/ui-mobile-core2.png`,fullPage:true});
  check('Mobile layout has no horizontal document overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  check('No browser script errors',errors.length===0);
  await fs.writeFile(`${output}/ui-verification-results.json`,JSON.stringify({checks,errors},null,2));
  console.log(JSON.stringify({passed:checks.length,checks,errors},null,2));
  await browser.close();
})().catch(err=>{console.error(err);process.exit(1);});
